export type AdminText = typeof bn

const LANG_KEY = 'ankashala-admin-lang'

export function readAdminLang(): AdminLang {
  return localStorage.getItem(LANG_KEY) === 'en' ? 'en' : 'bn'
}

export function saveAdminLang(lang: AdminLang) {
  localStorage.setItem(LANG_KEY, lang)
}
